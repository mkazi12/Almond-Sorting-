class Dataset(Base):
    __tablename__ = "datasets"
    __table_args__ = (_not_blank("name"),)

    id: Mapped[uuid.UUID] = _uuid_pk()
    name: Mapped[str] = mapped_column(unique=True)
    description: Mapped[str | None]
    almond_variety: Mapped[str | None]
