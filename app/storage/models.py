class InspectionSession(Base):
    """One analysis of a recording with one model version.

    Re-analyzing the same footage with a different model or interval creates
    another session; the video is never duplicated. ``sample_fps`` is the
    analysis cadence (1.0 = one frame per second) and is NULL for still
    images. The interval is in milliseconds from the recording's start;
    a NULL end means "to the end of the recording".
    """

    __tablename__ = "inspection_sessions"
    __table_args__ = (
        CheckConstraint("interval_start_ms >= 0", name="interval_start_non_negative"),
        CheckConstraint(
            "interval_end_ms IS NULL OR interval_end_ms > interval_start_ms",
            name="interval_end_after_start",
        ),
        CheckConstraint("sample_fps IS NULL OR sample_fps > 0", name="sample_fps_positive"),
        _unit_interval("confidence_threshold"),
        *_job_timing_checks(terminal=("completed", "failed", "cancelled"), active=("running",)),
        Index(None, "recording_id"),
        Index(None, "model_version_id"),
        Index(None, "created_at"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    recording_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("recordings.id"))
    model_version_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("model_versions.id"))
    name: Mapped[str | None]
    status: Mapped[JobStatus] = mapped_column(
        _enum(JobStatus, "job_status"), server_default=JobStatus.QUEUED.value
    )
    interval_start_ms: Mapped[int] = mapped_column(BigInteger, server_default=text("0"))
    interval_end_ms: Mapped[int | None] = mapped_column(BigInteger)
    sample_fps: Mapped[float | None]
    confidence_threshold: Mapped[float]
    started_at: Mapped[datetime | None]
    finished_at: Mapped[datetime | None]
    error_message: Mapped[str | None]
    created_by: Mapped[uuid.UUID | None] = _created_by()
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = _updated_at()

    recording: Mapped[Recording] = relationship()
    model_version: Mapped[ModelVersion] = relationship()
    categories: Mapped[list[Category]] = relationship(
        secondary="inspection_session_categories", order_by=Category.sort_order
    )
    # An 8-hour session holds ~28,800 frames; never load them all implicitly.
    frames: WriteOnlyMapped["Frame"] = relationship(back_populates="session", passive_deletes=True)


class Frame(Base):
    """One analyzed frame of a session, including frames with no detections.

    ``frame_index`` is the decoded frame number within ``media_file``; it is
    NULL when the media file is a still image. ``timestamp_ms`` is the offset
    from the start of the recording. The annotated image is never stored:
    draw ``detections`` over the decoded frame when it is displayed or
    exported. The unique constraint lets an interrupted analysis resume
    without duplicating frames.
    """

    __tablename__ = "frames"
    __table_args__ = (
        UniqueConstraint(
            "session_id", "media_file_id", "frame_index", postgresql_nulls_not_distinct=True
        ),
        CheckConstraint("frame_index IS NULL OR frame_index >= 0", name="frame_index_non_negative"),
        CheckConstraint("timestamp_ms >= 0", name="timestamp_non_negative"),
        Index(None, "session_id", "timestamp_ms"),
    )

    id: Mapped[int] = _bigint_pk()
    session_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("inspection_sessions.id", ondelete="CASCADE")
    )
    media_file_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("media_files.id"))
    frame_index: Mapped[int | None]
    timestamp_ms: Mapped[int] = mapped_column(BigInteger)

    session: Mapped[InspectionSession] = relationship(back_populates="frames")
    media_file: Mapped[MediaFile] = relationship()
    detections: Mapped[list["Detection"]] = relationship(
        back_populates="frame", cascade="all, delete-orphan", passive_deletes=True
    )


