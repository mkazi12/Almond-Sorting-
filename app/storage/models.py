def _enum(enum_class: type[enum.StrEnum], name: str) -> Enum:
    return Enum(
        enum_class,
        name=name,
        native_enum=False,
        create_constraint=True,
        # Fixed headroom so adding a longer value only changes the CHECK.
        length=32,
        values_callable=lambda members: [member.value for member in members],
        validate_strings=True,
    )


# --- Column and constraint helpers ------------------------------------------


def _uuid_pk() -> Mapped[uuid.UUID]:
    return mapped_column(primary_key=True, server_default=text("uuidv7()"))


def _bigint_pk() -> Mapped[int]:
    return mapped_column(BigInteger, Identity(always=False), primary_key=True)


def _created_at() -> Mapped[datetime]:
    return mapped_column(server_default=func.now())


def _updated_at() -> Mapped[datetime]:
    return mapped_column(server_default=func.now(), onupdate=func.now())


def _created_by() -> Mapped[uuid.UUID | None]:
    return mapped_column(ForeignKey("users.id"))


def _not_blank(column: str) -> CheckConstraint:
    return CheckConstraint(f"btrim({column}) <> ''", name=f"{column}_not_blank")


def _unit_interval(column: str, nullable: bool = False) -> CheckConstraint:
    condition = f"{column} >= 0 AND {column} <= 1"
    if nullable:
        condition = f"{column} IS NULL OR ({condition})"
    return CheckConstraint(condition, name=f"{column}_in_unit_interval")


def _bbox_checks(prefix: str = "", nullable: bool = False) -> tuple[CheckConstraint, ...]:
    """Normalized corners must satisfy 0 <= min < max <= 1 on both axes."""
    x0, y0, x1, y1 = (f"{prefix}{name}" for name in ("x_min", "y_min", "x_max", "y_max"))
    valid = f"0 <= {x0} AND {x0} < {x1} AND {x1} <= 1 AND 0 <= {y0} AND {y0} < {y1} AND {y1} <= 1"
    if not nullable:
        return (CheckConstraint(valid, name=f"{prefix}bbox_valid"),)
    # A CHECK passes when its expression is NULL, so a partly filled box
    # must be rejected explicitly rather than by the comparisons.
    all_null = f"{x0} IS NULL AND {y0} IS NULL AND {x1} IS NULL AND {y1} IS NULL"
    none_null = f"{x0} IS NOT NULL AND {y0} IS NOT NULL AND {x1} IS NOT NULL AND {y1} IS NOT NULL"
    return (
        CheckConstraint(f"({all_null}) OR ({none_null} AND {valid})", name=f"{prefix}bbox_valid"),
    )


def _relative_path_check(column: str) -> CheckConstraint:
    """Forward-slash relative path: no leading slash, drive, backslash, '.' or '..'."""
    return CheckConstraint(
        rf"{column} ~ '^[^/\\]+(/[^/\\]+)*$' "
        rf"AND {column} !~ '(^|/)\.\.?(/|$)' "
        rf"AND {column} !~ '^[A-Za-z]:'",
        name=f"{column}_relative",
    )


def _job_timing_checks(terminal: tuple[str, ...], active: tuple[str, ...]) -> tuple[CheckConstraint, ...]:
    terminal_sql = ", ".join(f"'{status}'" for status in terminal)
    active_sql = ", ".join(f"'{status}'" for status in active)
    return (
        CheckConstraint(
            f"(status IN ({terminal_sql})) = (finished_at IS NOT NULL)",
            name="finished_at_matches_status",
        ),
        CheckConstraint(
            f"status NOT IN ({active_sql}) OR started_at IS NOT NULL",
            name="active_has_started_at",
        ),
        CheckConstraint(
            "finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at",
            name="finished_after_started",
        ),
        CheckConstraint(
            "status <> 'failed' OR error_message IS NOT NULL",
            name="failed_has_error_message",
        ),
    )


# --- People and reference data ----------------------------------------------


class User(Base):
    """An employee who can log in. Deactivate users instead of deleting them,
    because sessions, models, and datasets keep pointing at their creator."""

    __tablename__ = "users"
    __table_args__ = (_not_blank("employee_id"), _not_blank("display_name"))

    id: Mapped[uuid.UUID] = _uuid_pk()
    employee_id: Mapped[str] = mapped_column(unique=True)
    display_name: Mapped[str]
    role: Mapped[UserRole] = mapped_column(
        _enum(UserRole, "user_role"), server_default=UserRole.OPERATOR.value
    )
    # Argon2id hash. NULL means the account cannot log in until a password is set.
    password_hash: Mapped[str | None]
    is_active: Mapped[bool] = mapped_column(server_default=text("true"))
    last_login_at: Mapped[datetime | None]
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = _updated_at()


class Category(Base):
    """Something the system can detect (almond, rock, stick, ...).

    Seeded by the initial migration. Model versions map their numeric class
    indices to these rows through ``model_version_classes``.
    """

    __tablename__ = "categories"
    __table_args__ = (
        CheckConstraint("key ~ '^[a-z][a-z0-9_]*$'", name="key_format"),
        _not_blank("display_name"),
    )

    id: Mapped[int] = mapped_column(SmallInteger, Identity(always=False), primary_key=True)
    key: Mapped[str] = mapped_column(unique=True)
    display_name: Mapped[str]
    description: Mapped[str | None]
    kind: Mapped[CategoryKind] = mapped_column(_enum(CategoryKind, "category_kind"))
    sort_order: Mapped[int] = mapped_column(SmallInteger, server_default=text("0"))
    is_active: Mapped[bool] = mapped_column(server_default=text("true"))
    created_at: Mapped[datetime] = _created_at()


# --- Media -------------------------------------------------------------------


class MediaFile(Base):
    """One file beneath the media root: a video, image, weights file, or export.

    ``relative_path`` uses forward slashes on every OS. Video and image
    metadata columns are filled in when known.
    """

    __tablename__ = "media_files"
    __table_args__ = (
        _relative_path_check("relative_path"),
        CheckConstraint("sha256 ~ '^[0-9a-f]{64}$'", name="sha256_format"),
        CheckConstraint("size_bytes >= 0", name="size_bytes_non_negative"),
        CheckConstraint(
            "(width IS NULL AND height IS NULL) "
            "OR (width IS NOT NULL AND height IS NOT NULL AND width > 0 AND height > 0)",
            name="dimensions_valid",
        ),
        CheckConstraint("duration_ms IS NULL OR duration_ms >= 0", name="duration_non_negative"),
        CheckConstraint("fps IS NULL OR fps > 0", name="fps_positive"),
        CheckConstraint("frame_count IS NULL OR frame_count >= 0", name="frame_count_non_negative"),
        Index(None, "sha256"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    kind: Mapped[MediaKind] = mapped_column(_enum(MediaKind, "media_kind"))
    relative_path: Mapped[str] = mapped_column(unique=True)
    sha256: Mapped[str]
    size_bytes: Mapped[int] = mapped_column(BigInteger)
    content_type: Mapped[str | None]
    original_filename: Mapped[str | None]
    width: Mapped[int | None]
    height: Mapped[int | None]
    duration_ms: Mapped[int | None] = mapped_column(BigInteger)
    fps: Mapped[float | None]
    frame_count: Mapped[int | None]
    codec: Mapped[str | None]
    created_by: Mapped[uuid.UUID | None] = _created_by()
    created_at: Mapped[datetime] = _created_at()


