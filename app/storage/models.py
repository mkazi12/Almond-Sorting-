class EvaluationResult(Base):
    """One matched or unmatched box, for reviewing mistakes.

    A true positive pairs a prediction with a ground-truth annotation. A
    false positive is a prediction with no match. A false negative is a
    missed annotation. A box predicted with the wrong class is recorded as
    one false positive plus one false negative, as in COCO evaluation.
    """

    __tablename__ = "evaluation_results"
    __table_args__ = (
        *_bbox_checks("pred_", nullable=True),
        _unit_interval("confidence", nullable=True),
        _unit_interval("iou", nullable=True),
        CheckConstraint(
            "(outcome = 'true_positive' AND dataset_annotation_id IS NOT NULL "
            "AND predicted_category_id IS NOT NULL AND confidence IS NOT NULL "
            "AND pred_x_min IS NOT NULL) "
            "OR (outcome = 'false_positive' AND dataset_annotation_id IS NULL "
            "AND predicted_category_id IS NOT NULL AND confidence IS NOT NULL "
            "AND pred_x_min IS NOT NULL) "
            "OR (outcome = 'false_negative' AND dataset_annotation_id IS NOT NULL "
            "AND predicted_category_id IS NULL AND confidence IS NULL "
            "AND pred_x_min IS NULL)",
            name="outcome_fields_consistent",
        ),
        Index(None, "evaluation_id", "outcome"),
    )

    id: Mapped[int] = _bigint_pk()
    evaluation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("model_evaluations.id", ondelete="CASCADE")
    )
    dataset_image_id: Mapped[int] = mapped_column(ForeignKey("dataset_images.id"))
    outcome: Mapped[EvaluationOutcome] = mapped_column(
        _enum(EvaluationOutcome, "evaluation_outcome")
    )
    dataset_annotation_id: Mapped[int | None] = mapped_column(ForeignKey("dataset_annotations.id"))
    predicted_category_id: Mapped[int | None] = mapped_column(
        SmallInteger, ForeignKey("categories.id")
    )
    confidence: Mapped[float | None]
    pred_x_min: Mapped[float | None]
    pred_y_min: Mapped[float | None]
    pred_x_max: Mapped[float | None]
    pred_y_max: Mapped[float | None]
    iou: Mapped[float | None]


